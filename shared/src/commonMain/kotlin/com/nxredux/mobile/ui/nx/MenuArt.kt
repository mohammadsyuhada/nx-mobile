/**
 * [tag]'s console logo (SFC and SUPA share one; so do MD and GPGX), or null for a tag no console claims. The Android
 * games console ([ANDROID_TAG], not a registry console) has its own: the Android wordmark with the robot head.
 */
fun consoleLogo(tag: String): DrawableResource? =
    if (tag == ANDROID_TAG) Res.drawable.menu_logo_android else CoreRegistry.consoleOf(tag)?.id?.let(consoleLogosById::get)

/** Pick a game's background mark: the app's own NX mark (`nx_mark.xml`, its 108-unit viewBox and strokes). */
internal val homePickMark: DrawableResource get() = Res.drawable.nx_mark

fun toolIcon(kind: ToolKind): DrawableResource = when (kind) {
    ToolKind.RETRO_ACHIEVEMENTS -> Res.drawable.menu_icon_achievements
    ToolKind.GAME_TIME -> Res.drawable.menu_icon_gametime
    ToolKind.ARTWORK -> Res.drawable.menu_icon_artwork
    ToolKind.CHEAT_DB -> Res.drawable.menu_icon_cheats
    ToolKind.DEVICE_SYNC -> Res.drawable.menu_icon_sync
    ToolKind.SETTINGS -> Res.drawable.menu_icon_settings
    ToolKind.APPS, ToolKind.APP -> Res.drawable.menu_icon_app
}

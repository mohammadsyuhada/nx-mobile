"""wiitdb.xml (GameTDB, https://www.gametdb.com) -> androidApp/src/main/assets/wii/controls.tsv.

Usage (from the repo root): python3 -I tools/gametdb/build_controls.py <wiitdb.xml> [out.tsv]
Flags: C = a Classic Controller is listed (required or optional), N = the Nunchuk is required, M = MotionPlus is
required, U = on tools/gametdb/upright.tsv (3-character game codes). Wii entries only (an empty <type>).
"""
import os
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_OUT = os.path.join(HERE, "..", "..", "androidApp", "src", "main", "assets", "wii", "controls.tsv")


def parse_upright(text):
    codes = set()
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        codes.add(line.split("\t", 1)[0].strip().upper())
    return codes


def parse_xml(xml_text):
    # A downloaded file: wiitdb.xml declares no DTD or entities, so refuse any that does (entity expansion attacks)
    # rather than parse it. The stdlib parser never fetches external entities; this closes the expansion case.
    if "<!DOCTYPE" in xml_text or "<!ENTITY" in xml_text:
        raise ValueError("wiitdb.xml with a DTD or entities: refusing to parse")
    return ET.fromstring(xml_text)


def rows(xml_text, upright):
    root = parse_xml(xml_text)
    out = {}
    for game in root.findall("game"):
        if (game.findtext("type") or "").strip():
            continue
        gid = (game.findtext("id") or "").strip().upper()
        if len(gid) != 6:
            continue
        controls = [(c.get("type"), c.get("required") == "true") for c in game.findall("input/control")]
        flags = ""
        if any(t == "classiccontroller" for t, _ in controls):
            flags += "C"
        if any(t == "nunchuk" and req for t, req in controls):
            flags += "N"
        if any(t == "motionplus" and req for t, req in controls):
            flags += "M"
        if gid[:3] in upright:
            flags += "U"
        out[gid] = flags
    return sorted(out.items())


def render(xml_text, upright):
    version = parse_xml(xml_text).find("WiiTDB").get("version")
    lines = ["# GameTDB wiitdb %s, https://www.gametdb.com" % version,
             "# Generated by tools/gametdb/build_controls.py; do not edit. Flags: C classic, N nunchuk, M motionplus, U upright."]
    lines += ["%s\t%s" % (gid, flags) for gid, flags in rows(xml_text, upright)]
    return "\n".join(lines) + "\n"


def main(argv):
    if len(argv) < 2:
        sys.exit("usage: build_controls.py <wiitdb.xml> [out.tsv]")
    with open(argv[1], encoding="utf-8") as f:
        xml_text = f.read()
    with open(os.path.join(HERE, "upright.tsv"), encoding="utf-8") as f:
        upright = parse_upright(f.read())
    out = argv[2] if len(argv) > 2 else DEFAULT_OUT
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(render(xml_text, upright))


if __name__ == "__main__":
    main(sys.argv)
